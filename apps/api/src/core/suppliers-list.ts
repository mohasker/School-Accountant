const key = (v: string) => v.replace(/\s+/g, ' ').trim().toLowerCase();

/** Adds the standard suppliers a school does not have yet (by name); returns how many were added. */
export async function addStandardSuppliers(t: Tx, schoolId: string) {
  const have = new Set((await t.supplier.findMany({ where: { schoolId }, select: { name: true } })).map((s) => key(s.name)));
  const missing = STANDARD_SUPPLIERS.filter((n) => !have.has(key(n)));
  if (missing.length) await t.supplier.createMany({ data: missing.map((name) => ({ schoolId, name })) });
  return missing.length;
}
